#!/usr/bin/env node
// Run the formula search (viz/discover.js) from each starting logic and save the results.
//
//   node scripts/discover.js [--vars 2] [--ops 5] [--floors linear,affine,...]
//   node scripts/discover.js --regroup     (regroup saved results without searching again)
//
// Each starting logic is searched in its own process (in parallel). Results go to
// data/discoveries/<floor>.json; data/discoveries.json and viz/discoveries.js (the same data for
// the page) are rebuilt from every per-floor file present.
const path = require("path");
const fs = require("fs");
const { spawn } = require("child_process");
const D = require(path.join(__dirname, "..", "viz", "discover.js"));

const arg = (name, dflt) => { const i = process.argv.indexOf("--" + name); return i > 0 ? process.argv[i + 1] : dflt; };
const vars = +arg("vars", 2), maxOps = +arg("ops", 5);
const floors = arg("floors", Object.keys(D.FLOORS).join(",")).split(",");
const root = path.join(__dirname, "..");
const dir = path.join(root, "data", "discoveries");

function combine() {
  const order = Object.keys(D.FLOORS);
  const runs = order.filter(f => fs.existsSync(path.join(dir, f + ".json"))).map(f => JSON.parse(fs.readFileSync(path.join(dir, f + ".json"), "utf8")));
  const out = { generated: new Date().toISOString().slice(0, 10), vars: runs[0].vars, maxOps: runs[0].maxOps, runs };
  fs.writeFileSync(path.join(root, "data", "discoveries.json"), JSON.stringify(out, null, 1));
  fs.writeFileSync(path.join(root, "viz", "discoveries.js"), "// Generated by scripts/discover.js\nwindow.DISCOVERIES = " + JSON.stringify(out) + ";\n");
}

if (process.argv.includes("--regroup")) {
  for (const f of fs.readdirSync(dir).filter(f => f.endsWith(".json"))) {
    const file = path.join(dir, f);
    fs.writeFileSync(file, JSON.stringify(D.regroup(JSON.parse(fs.readFileSync(file, "utf8"))), null, 1));
  }
  combine();
} else if (process.argv.includes("--child")) {
  // One starting logic, in this process.
  const floor = floors[0], t0 = Date.now();
  let last = 0;
  const r = D.search({ floor, vars, maxOps, onProgress: (i, n) => {
    if (Date.now() - last > 15000) { last = Date.now(); process.stderr.write(`  ${floor}: ${i}/${n}\n`); }
  } });
  r.ms = Date.now() - t0;
  fs.writeFileSync(path.join(dir, floor + ".json"), JSON.stringify(r, null, 1));
  process.stderr.write(`${floor}: ${r.classes} tested, ${r.findings.length} groups, ${r.unsettled} unsettled, ${(r.ms / 1000).toFixed(0)} s\n`);
} else {
  fs.mkdirSync(dir, { recursive: true });
  const t0 = Date.now();
  const kids = floors.map(floor => new Promise((resolve, reject) => {
    const p = spawn(process.execPath, [__filename, "--child", "--floors", floor, "--vars", String(vars), "--ops", String(maxOps)], { stdio: ["ignore", "inherit", "inherit"] });
    p.on("exit", code => code === 0 ? resolve() : reject(new Error(floor + " exited with " + code)));
  }));
  Promise.all(kids).then(() => {
    combine();
    process.stderr.write(`done in ${Math.round((Date.now() - t0) / 1000)} s\n`);
  }, err => { process.stderr.write(err.message + "\n"); process.exit(1); });
}
